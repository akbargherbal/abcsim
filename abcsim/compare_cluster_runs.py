"""compare_cluster_runs.py -- lead-only vs vocal-only clustering.

Reads out/clusters.json and out/vocal/clusters.json (written by
cluster_dups.py) and writes out/vocal/clusters_lead_vs_vocal.md.

The comparison is pair-based: a pair is "shared" if the two songs are in the
same cluster in both runs.  A vocal-only pair is a candidate the lead-voice
comparison missed (for example, Ins-lead vs Vocal-lead songs).

Usage:
    python abcsim/compare_cluster_runs.py out
"""
import argparse
import json
from pathlib import Path


def pair_sets(clusters):
    pairs = set()
    pair_cluster = {}
    for c in clusters['clusters']:
        ids = sorted(m['id'] for m in c['members'])
        for i, a in enumerate(ids):
            for b in ids[i + 1:]:
                pairs.add((a, b))
                pair_cluster[(a, b)] = c['id']
    return pairs, pair_cluster


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('outd', nargs='?', default='out')
    args = ap.parse_args(argv)
    outd = Path(args.outd)
    lead_path = outd / 'clusters.json'
    vocal_path = outd / 'vocal' / 'clusters.json'
    if not lead_path.exists() or not vocal_path.exists():
        raise SystemExit('need %s and %s' % (lead_path, vocal_path))
    lead = json.loads(lead_path.read_text(encoding='utf-8'))
    vocal = json.loads(vocal_path.read_text(encoding='utf-8'))
    lp, lc = pair_sets(lead)
    vp, vc = pair_sets(vocal)
    shared = lp & vp
    lead_only = lp - vp
    vocal_only = vp - lp

    def cluster_by_id(data, cid):
        return next(c for c in data['clusters'] if c['id'] == cid)

    L = []
    L.append('# Lead vs vocal clustering')
    L.append('')
    L.append('Generated by `abcsim/compare_cluster_runs.py`.')
    L.append('')
    L.append('The lead run compares each song\'s most-note voice (82 songs use `Ins` as')
    L.append('lead). The vocal run compares only the `Vocal` voice and skips 26 songs with')
    L.append('no usable vocal. Pairs here are co-clustered song pairs.')
    L.append('')
    L.append('| | lead | vocal |')
    L.append('|---|---|---|')
    L.append('| clusters | %d | %d |' % (lead['n_clusters'], vocal['n_clusters']))
    L.append('| songs in clusters | %d | %d |' % (lead['songs_in_clusters'], vocal['songs_in_clusters']))
    L.append('| songs removed | %d | %d |' % (lead['songs_removed'], vocal['songs_removed']))
    L.append('| co-clustered pairs | %d | %d |' % (len(lp), len(vp)))
    L.append('| shared pairs | %d | %d |' % (len(shared), len(shared)))
    L.append('')
    L.append('## Vocal-only pairs')
    L.append('')
    if vocal_only:
        L.append('These pairs are clustered in the vocal run but not in the lead run.')
        L.append('They are candidates the lead-only comparison missed; review before merging.')
        L.append('')
        L.append('| vocal cluster | A | B | z | coverage |')
        L.append('|---|---|---|---|---|')
        for a, b in sorted(vocal_only):
            c = cluster_by_id(vocal, vc[(a, b)])
            ma = next(m for m in c['members'] if m['id'] == a)
            mb = next(m for m in c['members'] if m['id'] == b)
            L.append('| %s | %s | %s | %s | %s |' % (
                c['id'], a, b, ma.get('z_to_rep') or mb.get('z_to_rep'),
                ma.get('coverage_to_rep') or mb.get('coverage_to_rep')))
    else:
        L.append('None: every vocal-run pair also exists in the lead run.')
    L.append('')
    L.append('## Lead-only pairs')
    L.append('')
    if lead_only:
        L.append('These pairs are clustered in the lead run but not in the vocal run. Some')
        L.append('are expected because the vocal index skips Ins-lead songs or the lead')
        L.append('alignment used the instrumental line.')
        L.append('')
        L.append('| lead cluster | A | B |')
        L.append('|---|---|---|')
        for a, b in sorted(lead_only):
            L.append('| %s | %s | %s |' % (lc[(a, b)], a, b))
    else:
        L.append('None: every lead-run pair also exists in the vocal run.')
    L.append('')
    L.append('## Clusters found only in vocal mode')
    L.append('')
    vocal_only_clusters = []
    for c in vocal['clusters']:
        ids = sorted(m['id'] for m in c['members'])
        cp = {(a, b) for i, a in enumerate(ids) for b in ids[i + 1:]}
        if cp and not (cp & lp):
            vocal_only_clusters.append(c)
    if vocal_only_clusters:
        for c in vocal_only_clusters:
            L.append('- **%s** (%d songs): %s' % (
                c['id'], c['size'], ', '.join(m['id'] for m in c['members'])))
    else:
        L.append('None: every vocal cluster has at least one pair also found in the lead run.')
    L.append('')
    L.append('## Clusters found only in lead mode')
    L.append('')
    lead_only_clusters = []
    for c in lead['clusters']:
        ids = sorted(m['id'] for m in c['members'])
        cp = {(a, b) for i, a in enumerate(ids) for b in ids[i + 1:]}
        if cp and not (cp & vp):
            lead_only_clusters.append(c)
    if lead_only_clusters:
        for c in lead_only_clusters:
            L.append('- **%s** (%d songs): %s' % (
                c['id'], c['size'], ', '.join(m['id'] for m in c['members'])))
    else:
        L.append('None.')
    L.append('')
    L.append('Do not merge these automatically. The plan requires human sign-off, and the')
    L.append('vocal run has its own representative selection and rescue pass.')
    L.append('')
    out = outd / 'vocal' / 'clusters_lead_vs_vocal.md'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(L), encoding='utf-8', newline='\n')
    print('lead pairs %d, vocal pairs %d, shared %d, vocal-only %d, lead-only %d' % (
        len(lp), len(vp), len(shared), len(vocal_only), len(lead_only)))
    print('wrote', out)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
